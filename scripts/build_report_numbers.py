#!/usr/bin/env python3
"""Write every number of the course report from the committed artifacts.

The report (``report/evibound_report.tex``) contains no hand-typed result. Each
number is looked up by key with ``\\V{key}``, and the tables and the effect
figure are generated here, so the report cannot drift from the records.

Sources (all committed, none of them frozen files that this script changes):

- ``artifacts/week8_main_results.json``            v2 formal test (the contract's test)
- ``artifacts/contract_outcomes_v2_v3.json``       outcomes the contract lists (post hoc tabulation)
- ``artifacts/week11_v3_holdout_results.json``     v3 holdout, preregistered decisions
- ``artifacts/week11_v3_review_reanalysis.json``   v3 reanalysis after the 2026-11-03 review
- ``artifacts/reproduction_*.json``                recomputation and second-machine re-run
- ``artifacts/episode_fingerprints_v2_formal_test.json.gz`` and ``data/scenarios_v2/test.jsonl``
  for facts about single episodes (which episodes make up the utility gap)
- ``artifacts/chain_attack_matrix_exploratory.json`` exploratory whole-chain matrix
- ``artifacts/v3_1_holdout_results.json``           v3.1 feedback ladder, preregistered decisions
- ``artifacts/v3_1_roles_record.json``              v3.1 exploratory arm (planner characters)
- ``artifacts/v3_1_dev_record.json``                v3.1 development runs before the freeze

Usage::

    python3 scripts/build_report_numbers.py            # rewrite report/generated/*.tex
    python3 scripts/build_report_numbers.py --check    # exit 1 if the committed files are stale
    python3 scripts/build_report_numbers.py --keys     # list every key and value
"""
