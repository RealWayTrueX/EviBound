def trace_archive():
    """Name, size and SHA-256 of the raw-trace archive, as recorded in docs/reproduction.md."""
    text = (ROOT / 'docs/reproduction.md').read_text(encoding='utf-8')
    found = re.search(r'\| `(evibound_raw_traces_\d+\.tar\.gz)` \| ([\d,]+) bytes \| `([0-9a-f]{64})` \|', text)
    if not found:
        raise ValueError('the trace archive row is missing from docs/reproduction.md')
    return found.group(1), found.group(2), found.group(3)


def table_artifacts():
    """Appendix table: each record and the first 16 hex digits of its SHA-256."""
    rows, previous = [], None

    def add(group, shown, digest):
        nonlocal previous
        if group != previous:
            if previous is not None:
                rows.append(r'\addlinespace[2pt]')
            rows.append(r'\multicolumn{2}{@{}l}{\emph{' + group + r'}} \\')
            previous = group
        rows.append(r'\path{' + shown + r'} & \texttt{' + digest[:16] + r'} \\')

    for group, path in ARTIFACT_ROWS:
        digest = hashlib.sha256((ROOT / path).read_bytes()).hexdigest()
        add(group, path[len('artifacts/'):] if path.startswith('artifacts/') else path, digest)
    name, _size, digest = trace_archive()
    add('Reproduction, model and raw traces', name, digest)
    return '\n'.join(rows) + '\n'


