def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--check', action='store_true', help='fail if the committed files are stale')
    parser.add_argument('--keys', action='store_true', help='print every key and value')
    args = parser.parse_args(argv)
    numbers, files = outputs()
    if args.keys:
        for key in sorted(numbers.values):
            print(f'{key}\t{numbers.values[key]}')
        return 0
    stale = [name for name, text in files.items()
             if not (OUT / name).exists() or (OUT / name).read_text(encoding='utf-8') != text]
    if args.check:
        for name in stale:
            print(f'stale: report/generated/{name}')
        print(f'{len(files) - len(stale)} of {len(files)} generated report files are current '
              f'({len(numbers.values)} numbers)')
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text, encoding='utf-8')
    print(f'wrote {len(files)} files to report/generated ({len(numbers.values)} numbers; '
          f'{len(stale)} changed)')
    return 0


