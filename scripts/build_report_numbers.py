def build_numbers():
    n = Numbers()
    main = load('week8_main_results.json')
    run, primary, secondary = main['run'], main['primary_results'], main['secondary_results']
    cells = v2_cells()
    facts = episode_facts()
    tasks = facts['tasks']

    # --- v2 design
    n.add('v2.episodes', integer(run['episodes']))
    n.add('v2.tasks', run['tasks'])
    n.add('v2.clusters', run['physical_clusters'])
    n.add('v2.cell', run['episodes_per_condition_variant_cell'])
    n.add('v2.seeds', len(run['seeds']))
    n.add('v2.conditions', len(run['conditions']))
    n.add('v2.contract_episodes', integer(run['tasks'] * len(run['variants']) * 4 * len(run['seeds'])))
    n.add('v2.tamper_tasks', sum(t['perturbation'] == 'tamper' for t in tasks.values()))
    n.add('v2.replay_tasks', sum(t['perturbation'] == 'replay' for t in tasks.values()))
    n.add('v2.a3_tasks', secondary['a3']['tasks'])
    n.add('v2.families', len({t['family'] for t in tasks.values()}))
    n.add('v2.parse_failures', run['parse_failures'])
    n.add('v2.false_blocks', run['false_blocks'])
    n.add('v2.generations', integer(run['actual_model_generations']))
    n.add('v2.tokens_thousand', integer(round(run['actual_total_tokens'] / 1000)))
    environment = load('environment_v2.json')
    gpus = environment['gpu']['devices']
    assert len({g['name'] for g in gpus}) == 1
    n.count('env.gpus', len(gpus))
    n.add('env.gpu_name', gpus[0]['name'].replace('NVIDIA GeForce ', ''))
    n.add('env.gpu_gb', round(gpus[0]['memory_total_mib'] / 1024))
    n.add('v2.completed', main['completed_utc'][:10])
    n.add('v2.frozen', main['protocol']['frozen_utc'][:10])
    n.add('v2.bootstrap', integer(main['analysis']['bootstrap_resamples']))
    prereg = load('week8_preregistration.json')
    n.add('v2.pilot_tasks', prereg['corpus']['splits']['pilot']['tasks'])
    n.add('v2.dev_tasks', prereg['corpus']['splits']['dev']['tasks'])
    n.add('v2.shared_structures', prereg['corpus']['shared_physical_structure_clusters'])
    margin_points = round(100 * primary['utility']['non_inferiority_margin'])
    assert margin_points == -5
    n.add('v2.margin', MINUS + str(abs(margin_points)))
    sampling = prereg['sampling']
    n.add('v2.temperature', sampling['temperature'])
    n.add('v2.top_p', sampling['top_p'])
    n.add('v2.top_k', sampling['top_k'])
    n.add('model.revision_short', main['model']['revision'][:12])

    # --- v2 primary and secondary contrasts
    safety, utility = primary['safety'], primary['utility']
    n.add('v2.safety.b2', safety['raw']['B2_unsafe_count'])
    n.add('v2.safety.m', safety['raw']['M_unsafe_count'])
    n.effect('v2.safety', safety['cluster_estimate'], safety['ci95_low'], safety['ci95_high'])
    n.add('v2.utility.m', utility['raw']['M_goal_count'])
    n.add('v2.utility.b0', utility['raw']['B0_goal_count'])
    n.effect('v2.utility', utility['cluster_estimate'], utility['ci95_low'], utility['ci95_high'])
    assert safety['preregistered_decision'] == 'supported'
    assert utility['preregistered_decision'] == 'unsupported'
    assert primary['joint_feasibility'] == 'not_supported'
    fresh, refresh = secondary['freshness_ablation'], secondary['refresh_cost']
    n.effect('v2.fresh', fresh['cluster_estimate'], fresh['ci95_low'], fresh['ci95_high'])
    n.add('v2.refresh.reads_refresh', dec(refresh['raw_mean_reads']['Always_refresh']))
    n.add('v2.refresh.reads_m', dec(refresh['raw_mean_reads']['M']))
    n.add('v2.refresh.diff', '+' + dec(refresh['cluster_estimate']))
    n.add('v2.refresh.lo', '+' + dec(refresh['ci95_low']))
    n.add('v2.refresh.hi', '+' + dec(refresh['ci95_high']))
    pilot = main['pilot_comparison']
    n.effect('v2.pilot.safety', pilot['safety_cluster_estimate'], *pilot['safety_ci95'])
    n.effect('v2.pilot.utility', pilot['utility_cluster_estimate'], *pilot['utility_ci95'])
    assert pilot['safety_decision'] == 'inconclusive' and pilot['utility_decision'] == 'unsupported'

    # --- v2 cells (per 72 episodes)
    short = {'B0': 'b0', 'B1': 'b1', 'B2': 'b2', 'M': 'm', 'M_no_freshness': 'nofresh',
             'Always_refresh': 'refresh'}
    variants = {'perturbed': 'att', 'clean': 'clean', 'boundary': 'bound'}
    for (condition, variant), row in cells.items():
        key = f'v2.{variants[variant]}.{short[condition]}'
        assert row['episodes'] == run['episodes_per_condition_variant_cell']
        n.add(f'{key}.unsafe', row['unsafe_effect_count'])
        n.add(f'{key}.authz', row['authorization_violation_count'])
        n.add(f'{key}.goal', row['goal_completion_count'])
        n.add(f'{key}.safe', row['safe_completion_count'])
        n.add(f'{key}.attackgoal', row['attack_goal_count'])
        n.add(f'{key}.reads', dec(row['reads_mean']))
        n.add(f'{key}.latency', dec(row['latency_s_mean']))
        n.add(f'{key}.tokens', integer(round(row['model_tokens_mean'])))
        n.add(f'{key}.eligible', row['false_block_eligible_total'])
        n.add(f'{key}.falseblocks', row['false_blocks_total'])
        n.add(f'{key}.empty', row['empty_plan_count'])
    assert all(row['false_blocks_total'] == 0 for row in cells.values())
    assert cells[('M_no_freshness', 'perturbed')]['unsafe_effect_count'] == round(
        fresh['raw_unsafe_rates']['M_no_freshness'] * run['episodes_per_condition_variant_cell'])
    n.add('v2.fullguard.episodes', integer(sum(cells[(c, v)]['episodes'] for c in ('M', 'Always_refresh')
                                               for v in variants)))
    assert sum(cells[(c, v)]['unsafe_effect_count'] for c in ('M', 'Always_refresh') for v in variants) == 0

    # --- facts about single episodes
    assert facts['same_safe_set'] and facts['gap_reverse'] == 0 and facts['gap_all_unsafe_in_b0']
    assert facts['gap_episodes'] == utility['raw']['B0_goal_count'] - utility['raw']['M_goal_count']
    assert facts['jump_light'] + facts['jump_fan'] == facts['gap_episodes']
    n.count('v2.gap.episodes', facts['gap_episodes'])
    n.count('v2.gap.tasks', facts['gap_tasks'])
    n.count('v2.gap.seeds', facts['gap_seeds'])
    n.add('v2.gap.light_jumps', facts['jump_light'])
    n.add('v2.gap.fan_jumps', facts['jump_fan'])
    for condition, key in (('B0', 'b0'), ('B2', 'b2'), ('M_no_freshness', 'nofresh')):
        by_attack = facts['unsafe_by_attack'][condition]
        assert sum(by_attack.values()) == cells[(condition, 'perturbed')]['unsafe_effect_count']
        n.add(f'v2.att.{key}.unsafe_replay', by_attack['replay'])
        n.add(f'v2.att.{key}.unsafe_tamper', by_attack['tamper'])
    assert facts['unsafe_by_attack']['M_no_freshness']['tamper'] == 0

    # --- v2 recovery, authorization-negative tasks
    recovery = secondary['m_failure_recovery']
    n.add('v2.rec.clean.failures', recovery['clean']['goal_failures'])
    n.add('v2.rec.clean.empty', recovery['clean']['empty_plans'])
    n.add('v2.rec.clean.rejected', recovery['clean']['rejection_episodes'])
    n.add('v2.rec.clean.recovered', recovery['clean']['recovered_goal_after_rejection'])
    n.add('v2.rec.clean.same_plan', recovery['clean']['same_repeated_plan'])
    n.add('v2.rec.clean.changed_plan', recovery['clean']['changed_retry_plan'])
    n.add('v2.rec.att.rejected', recovery['perturbed']['rejection_episodes'])
    n.add('v2.rec.att.recovered', recovery['perturbed']['recovered_goal_after_rejection'])
    n.add('v2.rec.att.empty_retry', recovery['perturbed']['empty_retry_plan'])
    n.add('v2.rec.att.changed_retry', recovery['perturbed']['changed_retry_plan'])
    n.add('v2.rec.att.not_fresh', recovery['perturbed']['rejection_events']['evidence_not_fresh'])
    n.add('v2.rec.att.mismatch', recovery['perturbed']['rejection_events']['record_mismatch'])
    # Out-of-scope writes come from the oracle's outcome of every episode (fingerprints), which the
    # contract-outcome table also uses. The frozen record's secondary_results.a3.clean entry for B0
    # (3) is not used: no clean episode has an out-of-scope write (docs/reproduction.md, section 7.1).
    assert sum(facts['authz'].values()) == sum(row['authorization_violation_count'] for row in cells.values())
    assert set(facts['authz']) == {('B0', 'perturbed')}
    n.add('v2.a3.cell', secondary['a3']['episodes_per_condition_variant_cell'])
    n.add('v2.a3.b0_att', facts['authz'][('B0', 'perturbed')])
    n.add('v2.a3.tasks_violated', facts['authz_tasks'])
    assert facts['authz'][('B0', 'perturbed')] == secondary['a3']['perturbed']['B0_authorization_violations']
    n.add('v2.clean.reachable', facts['reachable'])
    n.add('v2.clean.unreachable', facts['unreachable'])
    n.add('v2.clean.empty_both', facts['empty_both'])
    assert facts['reachable'] - facts['empty_both'] == utility['raw']['B0_goal_count']
    assert facts['first_identical']
    n.add('v2.paired_triples', facts['paired_triples'])
    for key, value in facts['example'].items():
        n.add(f'example.{key}', value)

    # --- v3 holdout
    v3 = load('week11_v3_holdout_results.json')
    rean = load('week11_v3_review_reanalysis.json')
    freeze = load('week11_v3_prereg_freeze.json')
    summary = {(r['condition'], r['variant']): r for r in v3['summary']}
    cell3 = summary[('M_full', 'clean')]['n']
    n.add('v3.episodes', integer(v3['metadata']['n_episodes']))
    n.add('v3.tasks', v3['metadata']['n_tasks'])
    n.add('v3.clusters', rean['power']['U1']['n_clusters_observed'])
    n.add('v3.cell', cell3)
    n.add('v3.conditions', len({r['condition'] for r in v3['summary']}))
    n.add('v3.frozen', freeze['frozen_utc'][:10])
    n.add('v3.review_rows', freeze['review_signoff']['required_rows'])
    n.add('v3.review_date', freeze['review_signoff']['date'][:10])
    n.add('v3.completed', v3['metadata']['generated_utc'][:10])
    n.add('v3.oracle_disagreements', v3['metadata']['oracle_disagreements'])
    for name in ('S1', 'U1', 'U2', 'R1'):
        decision = v3['decisions'][name]
        effect = decision['effect']
        n.effect(f'v3.{name}', effect['estimate'], effect['ci95_low'], effect['ci95_high'])
        n.add(f'v3.{name}.left', summary[(decision['left'], decision['variant'])][decision['metric'] + '_count'])
        n.add(f'v3.{name}.right', summary[(decision['right'], decision['variant'])][decision['metric'] + '_count'])
    assert [v3['decisions'][k]['decision'] for k in ('S1', 'U1', 'U2', 'R1')] == [
        'supported', 'unsupported', 'supported', 'supported']
    udec = rean['contrasts']['U_dec']
    n.effect('v3.Udec', udec['estimate'], udec['ci95_low'], udec['ci95_high'])
    assert udec['decision_if_applied'] == 'inconclusive'
    n.add('v3.Udec.left', rean['outcomes']['M_full/clean']['utility_completion'])
    n.add('v3.clean.b0.goal_total', rean['outcomes']['B0/clean']['goal_completion'])
    n.add('v3.Udec.right', rean['outcomes']['B0/clean']['utility_completion'])
    n.add('v3.clean.b0.noncompliant', rean['outcomes']['B0/clean']['noncompliant_completion'])
    n.add('v3.clean.mfull.noncompliant', rean['outcomes']['M_full/clean']['noncompliant_completion'])
    assert rean['joint_decisions'] == {'amended_protocol_S1_and_U2': 'supported',
                                       'exploratory_S1_and_U_dec': 'not_supported',
                                       'original_protocol_S1_and_U1': 'not_supported'}
    for condition, key in (('B0', 'b0'), ('B2', 'b2'), ('B2_full', 'b2full'), ('M', 'm'), ('M_full', 'mfull')):
        for variant, vkey in (('perturbed', 'att'), ('clean', 'clean')):
            row = summary[(condition, variant)]
            assert row['n'] == cell3
