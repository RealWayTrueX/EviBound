# ------------------------------------------------------------------ formats
def integer(value):
    return f'{int(value):,}'


def pp(value, sign=True):
    """A proportion as percentage points with one decimal: 0.3636 -> +36.4."""
    points = round(float(value) * 100, 1)
    if points == 0:
        return '0.0'
    body = f'{abs(points):.1f}'
    if points < 0:
        return MINUS + body
    return ('+' if sign else '') + body


def pct(count, total):
    return f'{100 * count / total:.1f}'


WORDS = ('zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven',
         'twelve', 'thirteen', 'fourteen', 'fifteen')


def dec(value, digits=2):
    return f'{float(value):.{digits}f}'


def cond(name):
    """A condition name as the report typesets it."""
    return r'\cond{' + name.replace('_', r'\_') + '}'


class Numbers:
    """The key -> text table behind ``\\V{key}``."""

    def __init__(self):
        self.values = {}

    def add(self, key, text):
        if key in self.values:
            raise KeyError(f'duplicate report key: {key}')
        self.values[key] = str(text)

    def count(self, key, value):
        """A small count, also available spelled out as ``key.word``."""
        self.add(key, value)
        self.add(f'{key}.word', WORDS[value])

    def effect(self, key, estimate, low, high):
        self.add(f'{key}.est', pp(estimate))
        self.add(f'{key}.lo', pp(low))
        self.add(f'{key}.hi', pp(high))

    def tex(self):
        lines = ['% Generated by scripts/build_report_numbers.py from the committed artifacts.',
                 '% Do not edit: change the script or the report text, then rebuild.']
        for key in sorted(self.values):
            lines.append(r'\expandafter\def\csname ev@' + key + r'\endcsname{' + self.values[key] + '}')
        return '\n'.join(lines) + '\n'


