def table_chain():
    """Exploratory whole-chain matrix: worst attack form and planner per group of hops."""
    chain = load('chain_attack_matrix_exploratory.json')
    hop_of = {a['id']: a['hop'] for a in chain['attacks']}
    rows, covered = [], set()
    baseline = []
    for condition in ('B0', 'B2', 'M_full'):
        candidates = [r for r in chain['rows'] if r['attack'] == 'none' and r['condition'] == condition]
        baseline.append(f"{round(100 * max(r['harmed'] / r['episodes'] for r in candidates))}")
    rows.append('--- & No attack & --- & ' + ' & '.join(baseline) + r' \\')
    rows.append(r'\addlinespace[2pt]')
    previous = None
    for hop_ids, label, trusted in CHAIN_ROWS:
        forms = sorted({a['id'] for a in chain['attacks'] if a['hop'] in hop_ids and a.get('run', True)})
        covered.update(forms)
        cells = []
        for condition in ('B0', 'B2', 'M_full'):
            candidates = [r for r in chain['rows'] if r['attack'] in forms and r['condition'] == condition]
            share = max(r['harmed'] / r['episodes'] for r in candidates)
            cells.append(f'{round(100 * share)}')
        if previous is not None and trusted != previous:
            rows.append(r'\midrule')
        previous = trusted
        name = '--'.join((hop_ids[0], hop_ids[-1])) if len(hop_ids) > 1 else hop_ids[0]
        rows.append(f"{name} & {label} & {len(forms)} & " + ' & '.join(cells) + r' \\')
    ran = {a['id'] for a in chain['attacks'] if a['id'] != 'none' and a.get('run', True)}
    assert covered == ran, sorted(ran - covered)
    assert all(hop_of[a] for a in ran)
    return '\n'.join(rows) + '\n'


