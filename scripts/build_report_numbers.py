LEVEL = {'off': 'off', 'low': 'level~1', 'high': 'level~2'}
EXAMPLE = ('test_strong_ventilation_02', 11)     # the attacked episode walked through in the report


def writes_text(writes):
    if not writes:
        return 'no write'
    return ', '.join(f"{device} to {LEVEL[value]}" for device, value in writes)


def episode_facts():
    """Facts about single v2 episodes, from the committed fingerprints and the task file."""
    by_key = load_any([ART / 'episode_fingerprints_v2_formal_test.json.gz'], 'v2')
    rows = list(by_key.values())
    tasks = {}
    for line in (ROOT / 'data/scenarios_v2/test.jsonl').read_text(encoding='utf-8').splitlines():
        task = json.loads(line)
        tasks[task['task_id']] = task
    seeds = sorted({r['seed'] for r in rows})
    pairs = [(t, s) for t in tasks for s in seeds]

    def cell(condition, variant):
        return {(r['task_id'], r['seed']): r for r in rows
                if r['condition'] == condition and r['variant'] == variant}

    def in_scope(task):
        """Can the goal for the true presence be reached with writes inside the scope?"""
        goal = task['goal_present'] if task['initial']['presence'] else task['goal_absent']
        return all(task['initial'][d] == v or d in task['authorized'] for d, v in goal.items())

    b0, m = cell('B0', 'clean'), cell('M', 'clean')
    gap = [k for k in b0 if b0[k]['metrics']['goal_completion'] and not m[k]['metrics']['goal_completion']]
    reverse = [k for k in b0 if m[k]['metrics']['goal_completion'] and not b0[k]['metrics']['goal_completion']]
    jumps = Counter()
    for key in gap:
        state = {d: tasks[key[0]]['initial'][d] for d in ('light', 'fan')}
        for device, value in b0[key]['writes']:
            if state[device] == 'off' and value == 'high':
                jumps['R5' if device == 'light' else 'R4'] += 1
            state[device] = value
    same = ({k for k in b0 if b0[k]['metrics']['safe_completion']}
            == {k for k in m if m[k]['metrics']['goal_completion']})

    def unsafe_by_attack(condition):
        attacked = cell(condition, 'perturbed')
        return Counter(tasks[k[0]]['perturbation'] for k in attacked if attacked[k]['metrics']['unsafe_effect'])

    # Clean episodes: which can be completed inside the scope, and how they end without and with the guard.
    reachable = [k for k in pairs if in_scope(tasks[k[0]])]
    unreachable = [k for k in pairs if not in_scope(tasks[k[0]])]
    assert not any(b0[k]['metrics']['goal_completion'] or m[k]['metrics']['goal_completion'] for k in unreachable)
    b0_fail = {k for k in reachable if not b0[k]['metrics']['goal_completion']}
    m_fail = {k for k in reachable if not m[k]['metrics']['goal_completion']}
    assert b0_fail <= m_fail and m_fail - b0_fail == set(gap)
    assert all(not b0[k]['writes'] and not m[k]['writes'] for k in b0_fail)

    guarded = ('B2', 'M', 'M_no_freshness', 'Always_refresh')
    safe_b0 = {k for k in b0 if b0[k]['metrics']['safe_completion']}
    for condition in ('B1',) + guarded:
        clean = cell(condition, 'clean')
        assert not any(clean[k]['metrics']['goal_completion'] for k in unreachable), condition
        if condition in guarded:
            assert {k for k in clean if clean[k]['metrics']['goal_completion']} == safe_b0, condition

    # The conditions that share a prompt start from the identical first response.
    shared = ('B2', 'M', 'M_no_freshness', 'Always_refresh')
    variants = sorted({r['variant'] for r in rows})
    identical = all(by_key[(t, v, c, s)]['first'] == by_key[(t, v, 'B0', s)]['first']
                    for t, s in pairs for v in variants for c in shared)

    # Out-of-scope writes.
    authz = Counter((r['condition'], r['variant']) for r in rows if r['metrics']['authorization_violation'])
    authz_tasks = {r['task_id'] for r in rows if r['metrics']['authorization_violation']}

    # The worked example.
    task_id, seed = EXAMPLE
    task = tasks[task_id]
    episode = {c: by_key[(task_id, 'perturbed', c, seed)] for c in ('B0', 'B2', 'M')}
    assert task['perturbation'] == 'tamper' and task['initial']['presence'] is False
    assert episode['B0']['writes'] == episode['B2']['writes']
    assert episode['B0']['metrics']['unsafe_effect'] and episode['B2']['metrics']['unsafe_effect']
    assert episode['M']['metrics']['goal_completion'] and not episode['M']['metrics']['unsafe_effect']
    assert episode['M']['proposals'] > len(episode['M']['writes'])        # one proposal was refused
    example = {'initial': f"fan at {LEVEL[task['initial']['fan']]}, light {LEVEL[task['initial']['light']]}",
               'goal_true': f"light {LEVEL[task['goal_absent']['light']]}, fan {LEVEL[task['goal_absent']['fan']]}",
               'goal_other': f"light at {LEVEL[task['goal_present']['light']]}, fan at {LEVEL[task['goal_present']['fan']]}",
               'unguarded': writes_text(episode['B0']['writes']), 'guarded': writes_text(episode['M']['writes']),
               'context': task['context'], 'family': task['family'].replace('_', ' ')}

    return {'gap_episodes': len(gap), 'gap_tasks': len({k[0] for k in gap}),
            'gap_seeds': len({k[1] for k in gap}), 'gap_reverse': len(reverse),
            'gap_all_unsafe_in_b0': all(b0[k]['metrics']['unsafe_effect'] for k in gap),
            'jump_light': jumps['R5'], 'jump_fan': jumps['R4'], 'same_safe_set': same,
            'unsafe_by_attack': {c: unsafe_by_attack(c) for c in ('B0', 'B2', 'M_no_freshness')},
            'reachable': len(reachable), 'unreachable': len(unreachable), 'empty_both': len(b0_fail),
            'first_identical': identical, 'paired_triples': len(pairs) * len(variants),
            'authz': authz, 'authz_tasks': len(authz_tasks), 'example': example, 'tasks': tasks}


def v3_scope_facts():
    """v3 clean episodes split by whether the goal can be reached inside the scope (post hoc)."""
    by_key = load_any([ART / 'episode_fingerprints_v3_holdout.json.gz'], 'v3')
    tasks = {}
    for line in (ROOT / 'data/scenarios_v3/holdout.jsonl').read_text(encoding='utf-8').splitlines():
        task = json.loads(line)
        tasks[task['task_id']] = task

    def in_scope(task):
        goal = task['goal_present'] if task['initial']['presence'] else task['goal_absent']
        return all(task['initial'][d] == v or d in task['authorized'] for d, v in goal.items())

    out = Counter()
    for (task_id, variant, condition, _seed), row in by_key.items():
        if variant != 'clean' or condition not in ('B0', 'B2_full', 'M', 'M_full'):
            continue
        where = 'in' if in_scope(tasks[task_id]) else 'out'
        metrics = row['metrics']
        out[(condition, where, 'n')] += 1
        out[(condition, where, 'goal')] += metrics['goal_completion']
        out[(condition, where, 'safe')] += metrics['safe_completion']
        if where == 'out' and metrics['goal_completion']:
            # a goal outside the scope can only be reached with a write outside the scope
            assert metrics['authorization_violation'], (task_id, condition)
    return out


